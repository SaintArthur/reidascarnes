// Função pura de tradução, usável tanto pelo contexto (componentes) quanto por
// código fora de componentes (funções utilitárias, classes) via translateNow().
function translate(lang, key, params) {
  const dict = DICTIONARIES[lang] || DICTIONARIES['pt-BR'];
  let text = dict[key] ?? DICTIONARIES['pt-BR'][key] ?? key;
  if (params) {
    Object.keys(params).forEach(k => { text = text.split(`{${k}}`).join(params[k]); });
  }
  return text;
}

// Para uso fora de componentes React (ex.: apiCall, statusLabel, ErrorBoundary —
// uma classe, sem hooks). Lê o idioma atual direto do localStorage, a mesma
// fonte que LanguageProvider mantém sincronizada.
function translateNow(key, params) {
  return translate(localStorage.getItem('lang') || 'pt-BR', key, params);
}

// Mapa idioma do app -> locale tag do Intl/toLocaleString.
const LOCALE_MAP = { 'pt-BR': 'pt-BR', 'en': 'en-US', 'es': 'es-ES' };
function localeTag(lang) {
  return LOCALE_MAP[lang] || 'pt-BR';
}
// Para uso fora de componentes React, análogo a translateNow.
function currentLocale() {
  return localeTag(localStorage.getItem('lang') || 'pt-BR');
}
// Nomes de mês (long) do idioma ativo, index 0 = Janeiro/January/Enero.
function monthNames(lang, format = 'long') {
  const locale = localeTag(lang);
  return Array.from({ length: 12 }, (_, i) => new Date(2024, i, 1).toLocaleDateString(locale, { month: format }));
}
// Abreviações de dia da semana (Seg..Dom / Mon..Sun / Lun..Dom) do idioma ativo, começando na segunda-feira.
function weekdayAbbrevs(lang) {
  const locale = localeTag(lang);
  // 2024-01-01 é uma segunda-feira.
  return Array.from({ length: 7 }, (_, i) => new Date(2024, 0, 1 + i).toLocaleDateString(locale, { weekday: 'short' }));
}
// Nomes completos de dia da semana do idioma ativo, index 0 = Domingo/Sunday/Domingo.
function weekdayNamesFull(lang) {
  const locale = localeTag(lang);
  // 2024-01-07 é um domingo.
  return Array.from({ length: 7 }, (_, i) => new Date(2024, 0, 7 + i).toLocaleDateString(locale, { weekday: 'long' }));
}
// Iniciais de dia da semana (1 letra) do idioma ativo, index 0 = Domingo/Sunday/Domingo — para cabeçalhos de calendário no estilo D S T Q Q S S.
function weekdayNarrowSunFirst(lang) {
  const locale = localeTag(lang);
  return Array.from({ length: 7 }, (_, i) => new Date(2024, 0, 7 + i).toLocaleDateString(locale, { weekday: 'narrow' }));
}
// Traduz um identificador interno fixo 'Seg'..'Dom' (usado como chave de lookup/persistência
// em escalas semanais) para o rótulo de exibição no idioma ativo — mesma ordem de weekdayAbbrevs.
const PT_WEEKDAY_ABBR_ORDER = ['Seg', 'Ter', 'Qua', 'Qui', 'Sex', 'Sáb', 'Dom'];
function dayAbbrevDisplay(lang, ptAbbrev) {
  const idx = PT_WEEKDAY_ABBR_ORDER.indexOf(ptAbbrev);
  if (idx < 0) return ptAbbrev;
  return weekdayAbbrevs(lang)[idx];
}

const LanguageContext = __i18nCreateContext(null);

function LanguageProvider({ user, children }) {
  const [lang, setLangState] = __i18nUseState(() => (user && user.language) || localStorage.getItem('lang') || 'pt-BR');

  __i18nUseEffect(() => {
    if (user && user.language && user.language !== lang) setLangState(user.language);
    if (!user) {
      const fallback = localStorage.getItem('lang') || 'pt-BR';
      setLangState(fallback);
    }
    // eslint-disable-next-line
  }, [user && user.language, !!user]);

  __i18nUseEffect(() => {
    localStorage.setItem('lang', lang);
    document.documentElement.setAttribute('lang', lang);
  }, [lang]);

  const setLang = (next) => setLangState(next);
  const t = (key, params) => translate(lang, key, params);

  return <LanguageContext.Provider value={{ lang, setLang, t }}>{children}</LanguageContext.Provider>;
}

function useLang() {
  return __i18nUseContext(LanguageContext);
}
